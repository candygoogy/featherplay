//! The app's language. The UI's `@tr` strings and the Rust side's `tr!` strings come from
//! the same `po/<lang>/LC_MESSAGES/featherplay.po` files, bundled at build time; English is
//! the source text. Every `.po` there is bundled, so a language is added by adding its file.
//!
//! At start-up the language follows the Language setting (Settings > Window): "system" (the
//! default) takes the first of the system's languages that featherplay has (Windows' display
//! languages, or `LANGUAGE`, `LC_ALL`, `LC_MESSAGES` and `LANG` on Linux, from
//! `featherplay_platform::system::languages`), by its tag or its language alone but never in
//! another script (`zh-TW` doesn't take Simplified Chinese), and English otherwise; "en" or a bundled code picks one. Picking one applies on the spot: Slint
//! re-evaluates every `@tr`, and the texts Rust put on screen are filled in again
//! (`on_change`). Settings shows the row only once a language besides English is bundled.
//!
//! `qps-ploc` (Windows' own pseudo-locale name) is the test language: every string in
//! brackets, generated by `po/update.sh`. Only a debug build's catalogue has it (`build.rs`);
//! `FEATHERPLAY_LANGUAGE=qps-ploc` shows it, as that variable shows any bundled language
//! (or `en`) for one run, whatever the setting.

use std::cell::RefCell;

use featherplay_core::{i18n, tr};

/// The test language's code.
pub const PSEUDO: &str = "qps-ploc";

/// The setting's value for following the system, its default.
pub const SYSTEM: &str = "system";

/// The variable that shows a language for one run: `en` or a bundled code.
pub const OVERRIDE: &str = "FEATHERPLAY_LANGUAGE";

mod generated {
    include!(concat!(env!("OUT_DIR"), "/catalog.rs"));
}

/// An entry of the Language setting's list.
pub struct Choice {
    /// What the setting stores: [`SYSTEM`], "en", or a bundled code.
    pub code: &'static str,
    pub name: String,
}

/// Makes the bundled translations available to `tr!`; call it before any string is shown.
pub fn install() {
    i18n::install(&generated::CATALOG);
}

/// Whether there's a language to pick besides English: the test language doesn't count.
pub fn offered() -> bool {
    bundled().iter().any(|c| *c != PSEUDO)
}

/// "System (English)", naming the language System shows on this machine, then English and
/// the bundled languages by their own names; the test language only `with_pseudo`.
pub fn choices(with_pseudo: bool) -> Vec<Choice> {
    let system = name(&resolve(SYSTEM, &system_languages(), &bundled()));
    let mut out = vec![
        Choice {
            code: SYSTEM,
            name: tr!("System ({})", system),
        },
        Choice {
            code: "en",
            name: "English".into(),
        },
    ];
    out.extend(
        generated::CATALOG
            .languages
            .iter()
            .filter(|l| with_pseudo || l.code != PSEUDO)
            .map(|l| Choice {
                code: l.code,
                name: l.name.into(),
            }),
    );
    out
}

/// A shown language's name in itself: "" is English.
fn name(code: &str) -> String {
    generated::CATALOG
        .languages
        .iter()
        .find(|l| l.code == code)
        .map_or("English", |l| l.name)
        .into()
}

/// The language to show for `setting`, given the system's languages (`preferred`, most
/// preferred first) and the `bundled` codes: "" is English. "en" is English, and a bundled
/// code is itself; anything else ([`SYSTEM`], "" from older settings files, a code no longer
/// bundled) follows the system (`i18n::best_match`, English among the candidates, so a
/// system that puts English first gets English). System never picks the test language.
pub fn resolve(setting: &str, preferred: &[String], bundled: &[&str]) -> String {
    if setting == "en" {
        return String::new();
    }
    if setting != SYSTEM && bundled.contains(&setting) {
        return setting.into();
    }
    let candidates: Vec<&str> = std::iter::once("en")
        .chain(bundled.iter().copied().filter(|c| *c != PSEUDO))
        .collect();
    match i18n::best_match(preferred, &candidates) {
        Some(code) if code != "en" => code.into(),
        _ => String::new(),
    }
}

/// [`resolve`], unless `forced` ([`OVERRIDE`]'s value) names English or a bundled language
/// (the test language too): then that one.
pub fn choose(
    setting: &str,
    forced: Option<&str>,
    preferred: &[String],
    bundled: &[&str],
) -> String {
    match forced.map(str::trim) {
        Some("en") => String::new(),
        Some(code) if bundled.contains(&code) => code.into(),
        _ => resolve(setting, preferred, bundled),
    }
}

/// The system's languages, most preferred first.
pub fn system_languages() -> Vec<String> {
    featherplay_platform::system::languages()
}

/// The bundled codes, English not included.
pub fn bundled() -> Vec<&'static str> {
    generated::CATALOG
        .languages
        .iter()
        .map(|l| l.code)
        .collect()
}

/// The language `setting` stands for on this machine now ("" is English).
pub fn for_setting(setting: &str) -> String {
    let forced = std::env::var(OVERRIDE).ok();
    choose(setting, forced.as_deref(), &system_languages(), &bundled())
}

thread_local! {
    /// What fills in texts Rust made for the window, run again after a language change.
    static REFILL: RefCell<Vec<Box<dyn Fn()>>> = const { RefCell::new(Vec::new()) };
}

/// Runs `refill` after every language change, on this (the UI) thread: for texts Rust put
/// in the window that stay there, such as a list Settings shows.
pub fn on_change(refill: impl Fn() + 'static) {
    REFILL.with(|r| r.borrow_mut().push(Box::new(refill)));
}

/// Shows `code` ("" or "en" for English) in the UI and the Rust side's strings. The UI's
/// part needs a window to exist already.
pub fn apply(code: &str) {
    if !i18n::select(code) {
        log!("language {code}: not bundled");
    }
    if let Err(e) = slint::select_bundled_translation(code) {
        log!("language {code}: {e}");
    }
    REFILL.with(|r| r.borrow().iter().for_each(|refill| refill()));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_setting_resolves_to_a_bundled_language_or_english() {
        // (case, setting, system languages, bundled, want); "" is English.
        let cases: [(&str, &str, &str, &[&str], &str); 10] = [
            (
                "first bundled",
                SYSTEM,
                "fr-FR de-DE en-US",
                &["de", "pl"],
                "de",
            ),
            ("none bundled", SYSTEM, "fr-FR en-US", &["de"], ""),
            ("English first", SYSTEM, "en-US de-DE", &["de"], ""),
            (
                "exact region wins",
                SYSTEM,
                "pt-BR",
                &["pt", "pt-BR"],
                "pt-BR",
            ),
            ("region matches base", SYSTEM, "pt-BR", &["pt"], "pt"),
            ("never the test one", SYSTEM, "qps-ploc", &[PSEUDO], ""),
            ("older files' empty value", "", "de-DE", &["de"], "de"),
            ("English overrides", "en", "de-DE", &["de"], ""),
            ("a pick overrides", "pl", "de-DE", &["de", "pl"], "pl"),
            ("pick gone: system", "pl", "de-DE", &["de"], "de"),
        ];
        for (case, setting, preferred, bundled, want) in cases {
            let preferred: Vec<String> = preferred.split(' ').map(String::from).collect();
            assert_eq!(resolve(setting, &preferred, bundled), want, "{case}");
        }
    }

    #[test]
    fn the_variable_shows_a_bundled_language_or_english_whatever_the_setting() {
        let de = vec!["de-DE".to_string()];
        let bundled = ["de", PSEUDO];
        assert_eq!(choose("en", Some(PSEUDO), &de, &bundled), PSEUDO);
        assert_eq!(choose(SYSTEM, Some("en"), &de, &bundled), "");
        assert_eq!(
            choose(SYSTEM, Some("xx"), &de, &bundled),
            "de",
            "not bundled: ignored"
        );
    }

    #[test]
    fn release_builds_keep_the_test_language_out_of_the_list() {
        assert!(choices(false).iter().all(|c| c.code != PSEUDO));
    }
}
