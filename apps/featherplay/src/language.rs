//! The app's language. The UI's `@tr` strings and the Rust side's `tr!` strings come from
//! the same `po/<lang>/LC_MESSAGES/featherplay.po` files, bundled at build time; English is
//! the source text. The Language setting (Settings > Window) is "Windows default" (the first
//! of the user's Windows display languages that's bundled, else English), English, or a
//! bundled language. Picking one applies on the spot: Slint re-evaluates every `@tr`, and the
//! page shown is filled again for the strings Rust put there.
//!
//! `qps-ploc` (Windows' own pseudo-locale name) is the test language: every string in
//! brackets, generated by `po/update.sh`. Only a debug build's catalogue has it (`build.rs`),
//! for the tests and Settings' list.

use std::cell::RefCell;

use featherplay_core::{i18n, tr};

/// The test language's code.
pub const PSEUDO: &str = "qps-ploc";

mod generated {
    include!(concat!(env!("OUT_DIR"), "/catalog.rs"));
}

/// An entry of the Language setting's list.
pub struct Choice {
    /// What the setting stores: "" for Windows default, "en", or a bundled code.
    pub code: &'static str,
    pub name: String,
}

/// Makes the bundled translations available to `tr!`; call it before any string is shown.
pub fn install() {
    i18n::install(&generated::CATALOG);
}

/// Windows default, English, then the bundled languages by their own names; the test
/// language only `with_pseudo`.
pub fn choices(with_pseudo: bool) -> Vec<Choice> {
    let mut out = vec![
        Choice {
            code: "",
            name: if cfg!(windows) {
                tr!("Windows default")
            } else {
                tr!("System default")
            }
            .into(),
        },
        Choice {
            code: "en",
            name: "English".into(),
        },
    ];
    out.extend(
        generated::CATALOG
            .languages
            .iter()
            .filter(|l| with_pseudo || l.code != PSEUDO)
            .map(|l| Choice {
                code: l.code,
                name: l.name.into(),
            }),
    );
    out
}

/// The language to show for `setting`, given the user's Windows display languages
/// (`preferred`, most preferred first) and the `bundled` codes: "" is English. A picked
/// language that's bundled wins; otherwise the first preferred language that's bundled,
/// exactly or by its language alone (`pt-BR` finds `pt`). Windows default never picks the
/// test language.
pub fn resolve(setting: &str, preferred: &[String], bundled: &[&str]) -> String {
    if setting == "en" {
        return String::new();
    }
    if !setting.is_empty() && bundled.contains(&setting) {
        return setting.into();
    }
    let base = |code: &str| {
        code.split(['-', '_'])
            .next()
            .unwrap_or("")
            .to_ascii_lowercase()
    };
    let candidates: Vec<&str> = bundled.iter().copied().filter(|c| *c != PSEUDO).collect();
    preferred
        .iter()
        .find_map(|want| {
            candidates
                .iter()
                .find(|c| c.eq_ignore_ascii_case(want))
                .or_else(|| candidates.iter().find(|c| base(c) == base(want)))
        })
        .map_or_else(String::new, |c| (*c).into())
}

/// The user's Windows display languages, most preferred first.
pub fn windows_languages() -> Vec<String> {
    sys_locale::get_locales().collect()
}

/// The bundled codes, English not included.
pub fn bundled() -> Vec<&'static str> {
    generated::CATALOG
        .languages
        .iter()
        .map(|l| l.code)
        .collect()
}

/// The language `setting` stands for on this machine ("" is English).
pub fn for_setting(setting: &str) -> String {
    resolve(setting, &windows_languages(), &bundled())
}

thread_local! {
    /// What fills in texts Rust made for the window, run again after a language change.
    static REFILL: RefCell<Vec<Box<dyn Fn()>>> = const { RefCell::new(Vec::new()) };
}

/// Runs `refill` after every language change, on this (the UI) thread: for texts Rust put
/// in the window that stay there, such as a list Settings shows.
pub fn on_change(refill: impl Fn() + 'static) {
    REFILL.with(|r| r.borrow_mut().push(Box::new(refill)));
}

/// Shows `code` ("" or "en" for English) in the UI and the Rust side's strings. The UI's
/// part needs a window to exist already.
pub fn apply(code: &str) {
    if !i18n::select(code) {
        log!("language {code}: not bundled");
    }
    if let Err(e) = slint::select_bundled_translation(code) {
        log!("language {code}: {e}");
    }
    REFILL.with(|r| r.borrow().iter().for_each(|refill| refill()));
}

#[cfg(test)]
mod tests {
    use super::*;

    fn langs(l: &[&str]) -> Vec<String> {
        l.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn windows_default_takes_the_first_display_language_that_is_bundled() {
        assert_eq!(
            resolve("", &langs(&["fr-FR", "de-DE", "en-US"]), &["de", "pl"]),
            "de"
        );
    }

    #[test]
    fn windows_default_is_english_when_no_display_language_is_bundled() {
        assert_eq!(resolve("", &langs(&["fr-FR", "en-US"]), &["de"]), "");
    }

    #[test]
    fn an_exact_regional_match_wins_over_the_language_alone() {
        assert_eq!(resolve("", &langs(&["pt-BR"]), &["pt", "pt-BR"]), "pt-BR");
    }

    #[test]
    fn a_regional_display_language_matches_the_bundled_language() {
        assert_eq!(resolve("", &langs(&["pt-BR"]), &["pt"]), "pt");
    }

    #[test]
    fn windows_default_never_picks_the_test_language() {
        assert_eq!(resolve("", &langs(&["qps-plocm"]), &[PSEUDO]), "");
    }

    #[test]
    fn english_overrides_windows() {
        assert_eq!(resolve("en", &langs(&["de-DE"]), &["de"]), "");
    }

    #[test]
    fn a_picked_language_overrides_windows() {
        assert_eq!(resolve("pl", &langs(&["de-DE"]), &["de", "pl"]), "pl");
    }

    #[test]
    fn a_picked_language_no_longer_bundled_falls_back_to_windows() {
        assert_eq!(resolve("pl", &langs(&["de-DE"]), &["de"]), "de");
    }

    #[test]
    fn settings_list_windows_default_and_english_first() {
        let codes: Vec<_> = choices(false).iter().take(2).map(|c| c.code).collect();
        assert_eq!(codes, ["", "en"]);
    }

    #[test]
    fn release_builds_keep_the_test_language_out_of_the_list() {
        assert!(choices(false).iter().all(|c| c.code != PSEUDO));
    }

    #[test]
    #[cfg_attr(not(debug_assertions), ignore)]
    fn debug_builds_list_the_test_language() {
        assert!(choices(true).iter().any(|c| c.code == PSEUDO));
    }
}
