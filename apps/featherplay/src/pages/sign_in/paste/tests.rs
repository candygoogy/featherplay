//! Shapes copied from the browsers' DevTools, with made-up values. The property tests
//! encode a header as each browser's copy does (their escaping, ported) and read it back.

use super::cookie_text;
use crate::pages::sign_in::check_cookie_header;
use proptest::prelude::*;

const NOW: i64 = 1_800_000_000;

fn read(text: &str) -> Result<String, &'static str> {
    cookie_text(text, NOW).map(|c| c.into_owned())
}

#[test]
fn chromes_bash_curl_gives_its_b_cookies() {
    let pasted = "curl 'https://music.youtube.com/youtubei/v1/browse?prettyPrint=false' \\
  -H 'accept: */*' \\
  -H 'accept-language: en-GB,en;q=0.9' \\
  -b 'PREF=f6=40000000&tz=Europe.Berlin; SID=g.a000-sid; SAPISID=abc/DEF' \\
  -H 'origin: https://music.youtube.com' \\
  --data-raw '{\"context\":{}}'";
    assert_eq!(
        read(pasted).unwrap(),
        "PREF=f6=40000000&tz=Europe.Berlin; SID=g.a000-sid; SAPISID=abc/DEF"
    );
    // Newer Chromium names the URL with --url; older ones send a cookie: header.
    let newer = "curl --url 'https://music.youtube.com/' \\\n  -H 'Cookie: SAPISID=x; HSID=y'";
    assert_eq!(read(newer).unwrap(), "SAPISID=x; HSID=y");
}

#[test]
fn chromes_cmd_curl_drops_its_carets() {
    let pasted = "curl ^\"https://music.youtube.com/^\" ^\n  -H ^\"accept: */*^\" ^\n  -b ^\"PREF=f6=4^&tz=Europe.Berlin; Q=^\"^\"a^\"^\"; SAPISID=abc/DEF^\" ^\n  -H ^\"user-agent: Mozilla/5.0 ^(Windows NT 10.0^)^\"";
    assert_eq!(
        read(pasted).unwrap(),
        "PREF=f6=4&tz=Europe.Berlin; Q=\"a\"; SAPISID=abc/DEF"
    );
}

#[test]
fn firefoxs_curls_give_their_cookie_header() {
    let bash = "curl 'https://music.youtube.com/' --compressed \\\n  -H 'User-Agent: Mozilla/5.0' \\\n  -H $'Cookie: A=it\\'s\\041; SAPISID=s'";
    assert_eq!(read(bash).unwrap(), "A=it's!; SAPISID=s");
    let cmd = "curl.exe ^\"https://music.youtube.com/^\" ^\n  -H ^\"Cookie: A=^\\^\"q^\\^\"; SAPISID=s^\"";
    assert_eq!(read(cmd).unwrap(), "A=\"q\"; SAPISID=s");
}

#[test]
fn powershell_gives_its_session_cookies() {
    let pasted = "$session = New-Object Microsoft.PowerShell.Commands.WebRequestSession
$session.UserAgent = \"Mozilla/5.0\"
$session.Cookies.Add((New-Object System.Net.Cookie(\"PREF\", \"tz=a`$b\", \"/\", \".youtube.com\")))
$session.Cookies.Add((New-Object System.Net.Cookie(\"SAPISID\", \"abc/DEF\", \"/\", \".youtube.com\")))
Invoke-WebRequest -UseBasicParsing -Uri \"https://music.youtube.com/\" `
-WebSession $session `
-Headers @{
\"accept\"=\"*/*\"
}";
    assert_eq!(read(pasted).unwrap(), "PREF=tz=a$b; SAPISID=abc/DEF");
}

#[test]
fn a_command_for_another_site_says_so() {
    for pasted in [
        "curl 'https://www.google.com/' -b 'SAPISID=x'",
        "curl 'https://notyoutube.com/' -b 'SAPISID=x'",
        "curl -b 'SAPISID=x'",
        "Invoke-WebRequest -Uri \"https://example.com/\"",
    ] {
        assert!(
            read(pasted).unwrap_err().contains("another site"),
            "{pasted}"
        );
    }
    assert!(
        read("curl 'https://www.youtube.com/'")
            .unwrap_err()
            .contains("no cookies")
    );
}

