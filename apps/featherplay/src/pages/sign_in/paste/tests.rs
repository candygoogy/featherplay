#[test]
fn a_bare_header_is_passed_on() {
    let header = "cookie: SID=a; SAPISID=b";
    assert_eq!(read(header).unwrap(), header);
}

#[test]
fn every_way_goes_through_the_header_checks() {
    let unsigned = "curl 'https://music.youtube.com/' -b 'SID=a; HSID=b'";
    assert!(
        check_cookie_header(unsigned)
            .unwrap_err()
            .contains("SAPISID")
    );
    let file = ".youtube.com\tTRUE\t/\tTRUE\t0\t__Secure-3PAPISID\tq\n";
    assert_eq!(check_cookie_header(file).unwrap(), "__Secure-3PAPISID=q");
}

// The browsers' escaping, ported from their DevTools.

fn chrome_posix(s: &str) -> String {
    if s.chars().any(|c| c.is_control() || c == '!' || c == '\'') {
        let mut out = String::from("$'");
        for c in s.chars() {
            match c {
                '\\' => out.push_str("\\\\"),
                '\'' => out.push_str("\\'"),
                '\n' => out.push_str("\\n"),
                '\r' => out.push_str("\\r"),
                c if c.is_control() || c == '!' => out.push_str(&format!("\\u{:04x}", c as u32)),
                c => out.push(c),
            }
        }
        out + "'"
    } else {
        format!("'{s}'")
    }
}

fn firefox_posix(s: &str) -> String {
    if s.chars()
        .any(|c| !(' '..='~').contains(&c) || c == '!' || c == '\'')
    {
        let mut out = String::from("$'");
        for c in s.chars() {
            match c {
                '\\' => out.push_str("\\\\"),
                '\'' => out.push_str("\\'"),
                '!' => out.push_str("\\041"),
                c if (c as u32) < 256 && !(' '..='~').contains(&c) => {
                    out.push_str(&format!("\\x{:02x}", c as u32))
                }
                c => out.push(c),
            }
        }
        out + "'"
    } else {
        format!("'{s}'")
    }
}

/// Chromium's `escapeStringWin`; `firefox` swaps its `""` for `\"` and its set of safe
/// characters for Firefox's.
fn win(s: &str, firefox: bool) -> String {
    let safe: &str = if firefox {
        "-_:=+~/.',?;()*` "
    } else {
        "_-:=+~/.',?;* "
    };
    let mut out = String::from("^\"");
    let mut chars = s.chars().peekable();
    while let Some(c) = chars.next() {
        let raw = match c {
            '\\' => "\\\\".to_owned(),
            '"' if firefox => "\\\"".to_owned(),
            '"' => "\"\"".to_owned(),
            c => c.to_string(),
        };
        for r in raw.chars() {
            if !r.is_ascii_alphanumeric() && !safe.contains(r) {
                out.push('^');
            }
            out.push(r);
        }
        if c == '%'
            && chars
                .peek()
                .is_some_and(|n| n.is_ascii_alphanumeric() || *n == '_')
        {
            out.push('^');
        }
    }
    out + "^\""
}

fn powershell(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        if "`$\"".contains(c) {
            out.push('`');
        }
        out.push(c);
    }
    out + "\""
}

/// RFC 6265's cookie-octet, which every browser keeps to (no quote, backslash, comma,
/// semicolon or space).
fn pairs() -> impl Strategy<Value = Vec<(String, String)>> {
    let pair = ("[A-Za-z0-9_-]{1,10}", "[!#-+\\--:<-\\[\\]-~]{0,16}");
    prop::collection::vec(pair, 0..6).prop_map(|mut v| {
        v.push(("SAPISID".into(), "abc/DEF".into()));
        v
    })
}

fn header(pairs: &[(String, String)]) -> String {
    let v: Vec<String> = pairs.iter().map(|(n, v)| format!("{n}={v}")).collect();
    v.join("; ")
}

proptest! {
    #![proptest_config(ProptestConfig::with_cases(64))]

    #[test]
    fn each_browsers_copy_reads_back_as_its_header(pairs in pairs()) {
        let h = header(&pairs);
        let url = "https://music.youtube.com/youtubei/v1/next?prettyPrint=false";
        let ws = |s: &str| win(s, false);
        let copies = [
            format!("curl --url {} \\\n  -H {} \\\n  -b {}", chrome_posix(url), chrome_posix("accept: */*"), chrome_posix(&h)),
            format!("curl --url {} ^\n  -H {} ^\n  -b {}", ws(url), ws("accept: */*"), ws(&h)),
            format!("curl {} \\\n  -H {}", firefox_posix(url), firefox_posix(&format!("Cookie: {h}"))),
            format!("curl.exe {} ^\n  -H {}", win(url, true), win(&format!("Cookie: {h}"), true)),
        ];
        for copy in &copies {
            prop_assert_eq!(&read(copy).unwrap(), &h, "{}", copy);
        }
        let mut ps = String::from("$session = New-Object Microsoft.PowerShell.Commands.WebRequestSession\n");
        for (n, v) in &pairs {
            ps += &format!("$session.Cookies.Add((New-Object System.Net.Cookie({}, {}, \"/\", \".youtube.com\")))\n", powershell(n), powershell(v));
        }
        ps += &format!("Invoke-WebRequest -UseBasicParsing -Uri {} `\n-WebSession $session", powershell(url));
        prop_assert_eq!(read(&ps).unwrap(), h);
    }

    #[test]
    fn a_cookies_file_keeps_the_last_of_each_name(pairs in pairs()) {
        let file: String = pairs
            .iter()
            .map(|(n, v)| format!("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t0\t{n}\t{v}\n"))
            .collect();
        let got = read(&file).unwrap();
        let got: Vec<&str> = got.split("; ").collect();
        // Each name once, with its last value.
        for (n, v) in &pairs {
            let last = pairs.iter().rev().find(|(m, _)| m == n).map(|(_, v)| v);
            prop_assert_eq!(got.iter().filter(|p| p.split('=').next() == Some(n)).count(), 1);
            if last == Some(v) {
                let pair = format!("{n}={v}");
                prop_assert!(got.contains(&pair.as_str()));
            }
        }
    }

    #[test]
    fn any_text_is_read_without_a_panic(text in "(curl |curl\\.exe |Invoke-WebRequest |)[ -~\t\n^\"'$`\\\\]{0,80}") {
        let _ = read(&text);
    }
}
